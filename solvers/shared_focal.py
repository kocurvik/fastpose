@njit(cache=True, fastmath=True)
def _solve_shared_focal_6pt(data, sample, models, workspace):
    x1_x, x1_y, x2_x, x2_y, pp1x, pp1y, pp2x, pp2y = data
    o = 0
    A = workspace[o:o + 54].reshape(6, 9)
    o += 54
    N = workspace[o:o + 27].reshape(3, 9)
    o += 27
    d = workspace[o:o + 27]
    o += 27
    sols = workspace[o:o + 45].reshape(15, 3)
    o += 45
    e = workspace[o:o + 9]
    o += 9
    Rbuf = workspace[o:o + 18].reshape(2, 3, 3)
    o += 18
    solver_ws = workspace[o:]

    for k in range(6):
        idx = sample[k]
        x = x1_x[idx] - pp1x
        y = x1_y[idx] - pp1y
        xp = x2_x[idx] - pp2x
        yp = x2_y[idx] - pp2y
        # PoseLib's generated solver uses Eigen's column-major vec(F):
        # [F00, F10, F20, F01, F11, F21, F02, F12, F22].
        A[k, 0] = x * xp
        A[k, 1] = x * yp
        A[k, 2] = x
        A[k, 3] = y * xp
        A[k, 4] = y * yp
        A[k, 5] = y
        A[k, 6] = xp
        A[k, 7] = yp
        A[k, 8] = 1.0
    if not _nullspace_6pt(A, N):
        return 0
    # PoseLib maps Eigen's column-major 9x3 nullspace matrix into a vector.
    for c in range(3):
        for r in range(9):
            d[9 * c + r] = N[c, r]

    n_sols = _solver_shared_focal_relpose_6pt(d, sols, solver_ws)
    count = 0
    for i in range(n_sols):
        inv_f_sq = sols[i, 2]
        if inv_f_sq <= 1e-12:
            continue
        focal = math.sqrt(1.0 / inv_f_sq)
        for j in range(9):
            e[j] = N[0, j] + sols[i, 0] * N[1, j] + sols[i, 1] * N[2, j]
        norm = 0.0
        for j in range(9):
            norm += e[j] * e[j]
        if norm < 1e-24:
            continue
        inv = 1.0 / math.sqrt(norm)
        for j in range(9):
            e[j] *= inv
        # Convert column-major F to row-major E = K^T F K with shared focal
        # and zero-centered coordinates.
        f00 = e[0]
        f10 = e[1]
        f20 = e[2]
        f01 = e[3]
        f11 = e[4]
        f21 = e[5]
        f02 = e[6]
        f12 = e[7]
        f22 = e[8]
        ff = focal * focal
        e[0] = ff * f00
        e[1] = ff * f01
        e[2] = focal * f02
        e[3] = ff * f10
        e[4] = ff * f11
        e[5] = focal * f12
        e[6] = focal * f20
        e[7] = focal * f21
        e[8] = f22
        if _pose_from_essential(e, (x1_x, x1_y, x2_x, x2_y), sample,
                                pp1x, pp1y, pp2x, pp2y, focal, focal,
                                models[count], Rbuf):
            models[count, 12] = focal
            models[count, 13] = focal
            count += 1
            if count == 15:
                break
    return count


