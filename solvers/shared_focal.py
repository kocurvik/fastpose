@njit(cache=True, fastmath=True)
def _nullspace_6pt(A, N):
    # 3-dimensional nullspace of the 6x9 epipolar system. The resulting N is
    # stored as rows, matching the local 5-point nullspace convention.
    U, s, Vt = np.linalg.svd(A)
    for r in range(3):
        norm = 0.0
        for c in range(9):
            v = Vt[6 + r, c]
            N[r, c] = v
            norm += v * v
        if norm < 1e-24:
            return False
        inv = 1.0 / math.sqrt(norm)
        for c in range(9):
            N[r, c] *= inv
    return True


@njit(cache=True, fastmath=True)
def _fill_coeffs(d, coeffs):
    for ci in range(280):
        coeffs[ci] = 0.0
    for ci in range(280):
        for ti in range(_COEFF_TERM_START[ci], _COEFF_TERM_START[ci + 1]):
            v = _COEFF_TERM_FACTOR[ti]
            ia = _COEFF_TERM_A[ti]
            if ia >= 0:
                v *= d[ia]
            ib = _COEFF_TERM_B[ti]
            if ib >= 0:
                v *= d[ib]
            ic = _COEFF_TERM_C[ti]
            if ic >= 0:
                v *= d[ic]
            coeffs[ci] += v


@njit(cache=True, fastmath=True)
def _solve_linear_31x15(C0, C1, C12):
    # C12 <- C0^-1 C1 via Gaussian elimination with partial pivoting.
    n = 31
    m = 15
    scale = 0.0
    for r in range(n):
        for c in range(n):
            v = abs(C0[r, c])
            if v > scale:
                scale = v
    if scale == 0.0:
        return False
    tol = 1e-12 * scale
    for r in range(n):
        for c in range(m):
            C12[r, c] = C1[r, c]
    for col in range(n):
        piv = col
        max_val = abs(C0[col, col])
        for r in range(col + 1, n):
            v = abs(C0[r, col])
            if v > max_val:
                max_val = v
                piv = r
        if max_val < tol:
            return False
        if piv != col:
            for c in range(col, n):
                t = C0[col, c]
                C0[col, c] = C0[piv, c]
                C0[piv, c] = t
            for c in range(m):
                t = C12[col, c]
                C12[col, c] = C12[piv, c]
                C12[piv, c] = t
        inv = 1.0 / C0[col, col]
        for r in range(col + 1, n):
            factor = C0[r, col] * inv
            if factor != 0.0:
                C0[r, col] = 0.0
                for c in range(col + 1, n):
                    C0[r, c] -= factor * C0[col, c]
                for c in range(m):
                    C12[r, c] -= factor * C12[col, c]
    for r in range(n - 1, -1, -1):
        inv = 1.0 / C0[r, r]
        for c in range(m):
            s = C12[r, c]
            for k in range(r + 1, n):
                s -= C0[r, k] * C12[k, c]
            C12[r, c] = s * inv
    return True


@njit(cache=True, fastmath=True)
def _charpoly_danilevsky_n(T, coef, row, tmp_row, n):
    for i in range(n - 1, 0, -1):
        piv_ind = i - 1
        piv = abs(T[i, i - 1])
        for j in range(i - 1):
            v = abs(T[i, j])
            if v > piv:
                piv = v
                piv_ind = j
        if piv < 1e-14:
            return False
        if piv_ind != i - 1:
            for c in range(n):
                t = T[piv_ind, c]
                T[piv_ind, c] = T[i - 1, c]
                T[i - 1, c] = t
            for r in range(n):
                t = T[r, piv_ind]
                T[r, piv_ind] = T[r, i - 1]
                T[r, i - 1] = t
        for c in range(n):
            row[c] = T[i, c]
        inv = 1.0 / row[i - 1]
        for r in range(i + 1):
            colv = T[r, i - 1]
            if colv != 0.0:
                f = colv * inv
                for c in range(n):
                    T[r, c] -= row[c] * f
                T[r, i - 1] = f
            else:
                T[r, i - 1] = 0.0
        for c in range(n):
            s = 0.0
            for k in range(n):
                s += row[k] * T[k, c]
            tmp_row[c] = s
        for c in range(n):
            T[i - 1, c] = tmp_row[c]
            T[i, c] = 0.0
        T[i, i - 1] = 1.0
    coef[n] = 1.0
    for k in range(n):
        coef[n - 1 - k] = -T[0, k]
    return True


@njit(cache=True, fastmath=True)
def _solve_7x7(A, b, x):
    n = 7
    scale = 0.0
    for r in range(n):
        for c in range(n):
            v = abs(A[r, c])
            if v > scale:
                scale = v
    if scale == 0.0:
        return False
    tol = 1e-12 * scale
    for col in range(n):
        piv = col
        max_val = abs(A[col, col])
        for r in range(col + 1, n):
            v = abs(A[r, col])
            if v > max_val:
                max_val = v
                piv = r
        if max_val < tol:
            return False
        if piv != col:
            for c in range(col, n):
                t = A[col, c]
                A[col, c] = A[piv, c]
                A[piv, c] = t
            tb = b[col]
            b[col] = b[piv]
            b[piv] = tb
        inv = 1.0 / A[col, col]
        for r in range(col + 1, n):
            factor = A[r, col] * inv
            if factor != 0.0:
                A[r, col] = 0.0
                for c in range(col + 1, n):
                    A[r, c] -= factor * A[col, c]
                b[r] -= factor * b[col]
    for r in range(n - 1, -1, -1):
        s = b[r]
        for c in range(r + 1, n):
            s -= A[r, c] * x[c]
        x[r] = s / A[r, r]
    return True


@njit(cache=True, fastmath=True)
def _fast_eigenvector_solution(lam, AM, sol):
    ind = (2, 3, 4, 6, 8, 9, 11, 14)
    A = np.empty((7, 7))
    b = np.empty(7)
    x = np.empty(7)
    z0 = lam
    z1 = z0 * z0
    z2 = z1 * z0
    for ii in range(8):
        row = ind[ii]
        cols = (2, 6, -1, -2, 14, -3, -4, -5)
        vals = np.empty(8)
        vals[0] = AM[row, 2]
        vals[1] = AM[row, 6]
        vals[2] = z0 * AM[row, 4] + AM[row, 5]
        vals[3] = AM[row, 1] + z0 * AM[row, 3]
        vals[4] = AM[row, 14]
        vals[5] = z0 * AM[row, 11] + AM[row, 13]
        vals[6] = z1 * AM[row, 9] + z0 * AM[row, 10] + AM[row, 12]
        vals[7] = AM[row, 0] + z0 * AM[row, 7] + z1 * AM[row, 8]
        if ii == 0:
            vals[0] -= z0
        elif ii == 3:
            vals[1] -= z0
        elif ii == 2:
            vals[2] -= z1
        elif ii == 1:
            vals[3] -= z1
        elif ii == 7:
            vals[4] -= z0
        elif ii == 6:
            vals[5] -= z1
        elif ii == 5:
            vals[6] -= z2
        elif ii == 4:
            vals[7] -= z2
        if ii < 7:
            for c in range(7):
                A[ii, c] = vals[c]
            b[ii] = -vals[7]
    if not _solve_7x7(A, b, x):
        return False
    sol[0] = x[3]
    sol[1] = z0
    sol[2] = x[6]
    return True


